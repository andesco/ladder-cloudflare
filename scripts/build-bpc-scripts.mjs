#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';

const VENDOR_ROOT = path.resolve('src/vendor/bpc');
const OUTPUT_FILE = path.resolve('src/runtime/bpc-scripts.generated.js');
const LOCAL_FILES = [
  'contentScript_de.js',
  'contentScript_en.js',
  'contentScript_es.pt.js',
  'contentScript_fi.se.js',
  'contentScript_fr.js',
  'contentScript_it.js',
  'contentScript_nl.js',
  'contentScript_pl.js',
];

function readVendorFile(relativePath) {
  const filename = path.join(VENDOR_ROOT, relativePath);
  if (!fs.existsSync(filename)) {
    throw new Error(`Missing vendored BPC source: ${filename}`);
  }
  return fs.readFileSync(filename, 'utf8');
}

const generated = {
  core: readVendorFile('contentScript.js'),
  purify: readVendorFile('lib/purify.min.js'),
  local: Object.fromEntries(
    LOCAL_FILES.map((filename) => [filename.replace(/^contentScript_|\.js$/g, ''), readVendorFile(`cs_local/${filename}`)]),
  ),
};

const output = [
  '// Auto-generated by scripts/build-bpc-scripts.mjs. Do not edit by hand.',
  `export const BPC_CONTENT_SCRIPT_SOURCE = ${JSON.stringify(generated.core)};`,
  `export const BPC_PURIFY_SOURCE = ${JSON.stringify(generated.purify)};`,
  `export const BPC_LOCAL_SCRIPT_SOURCES = ${JSON.stringify(generated.local)};`,
  '',
].join('\n');

fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
fs.writeFileSync(OUTPUT_FILE, output);
console.log(
  `Generated ${path.relative(process.cwd(), OUTPUT_FILE)} from ${LOCAL_FILES.length + 2} vendored BPC scripts`,
);
